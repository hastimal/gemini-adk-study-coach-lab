"""Prometheus metrics instruments and registry for study-coach."""

import logging

from prometheus_client import (
    REGISTRY,
    CollectorRegistry,
    Counter,
    Histogram,
    start_http_server,
)

logger = logging.getLogger(__name__)

# Dedicated registry to prevent collision with default Python / GC metrics
study_coach_registry: CollectorRegistry = REGISTRY

# 1. Total application requests
REQUESTS_TOTAL = Counter(
    "study_coach_requests_total",
    "Total incoming user requests across all workflows.",
    ["workflow", "status"],
    registry=study_coach_registry,
)

# 2. Workflow request duration
REQUEST_DURATION_SECONDS = Histogram(
    "study_coach_request_duration_seconds",
    "Duration of study-coach workflow requests in seconds.",
    ["workflow", "status"],
    buckets=(0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0, 20.0, 30.0),
    registry=study_coach_registry,
)

# 3. Agent calls
AGENT_CALLS_TOTAL = Counter(
    "study_coach_agent_calls_total",
    "Total invocations of Google ADK specialized agents.",
    ["agent", "model"],
    registry=study_coach_registry,
)

# 4. Agent errors
AGENT_ERRORS_TOTAL = Counter(
    "study_coach_agent_errors_total",
    "Total failed or erroring agent executions.",
    ["agent", "error_type"],
    registry=study_coach_registry,
)

# 5. Tool calls
TOOL_CALLS_TOTAL = Counter(
    "study_coach_tool_calls_total",
    "Total invocations of deterministic curriculum and grading tools.",
    ["tool", "status"],
    registry=study_coach_registry,
)

# 6. Quiz submissions
QUIZ_SUBMISSIONS_TOTAL = Counter(
    "study_coach_quiz_submissions_total",
    "Total formative quick-check or practice quiz submissions.",
    ["quiz_type"],
    registry=study_coach_registry,
)

# 7. Quiz generation duration
QUIZ_GENERATION_DURATION_SECONDS = Histogram(
    "study_coach_quiz_generation_duration_seconds",
    "Latency of quiz generation from Quiz Generator agent.",
    ["quiz_type"],
    buckets=(0.5, 1.0, 2.0, 5.0, 10.0, 15.0, 30.0),
    registry=study_coach_registry,
)

# 8. Adaptive replanning events
REPLANNING_TOTAL = Counter(
    "study_coach_replanning_total",
    "Total adaptive replanning executions triggered by weak topic diagnostic analysis.",
    registry=study_coach_registry,
)

# 9. Document RAG operations
DOCUMENT_OPERATIONS_TOTAL = Counter(
    "study_coach_document_operations_total",
    "Total document operations performed in active sessions.",
    ["operation", "file_type", "status"],
    registry=study_coach_registry,
)

DOCUMENT_RETRIEVAL_LATENCY_SECONDS = Histogram(
    "study_coach_document_retrieval_latency_seconds",
    "Latency of local document search and chunk retrieval.",
    buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0),
    registry=study_coach_registry,
)

CHAT_MESSAGES_TOTAL = Counter(
    "study_coach_chat_messages_total",
    "Total multi-turn chat messages processed by Study Coach.",
    ["role", "routed_agent"],
    registry=study_coach_registry,
)


# Optional model token counters (only incremented when actual token metadata is returned)
MODEL_INPUT_TOKENS_TOTAL = Counter(
    "study_coach_model_input_tokens_total",
    "Total input tokens consumed by Gemini models when reported in response metadata.",
    ["model"],
    registry=study_coach_registry,
)

MODEL_OUTPUT_TOKENS_TOTAL = Counter(
    "study_coach_model_output_tokens_total",
    "Total output tokens generated by Gemini models when reported in response metadata.",
    ["model"],
    registry=study_coach_registry,
)

_HTTP_SERVER_STARTED: bool = False


def init_metrics() -> None:
    """Pre-initializes metric labels so metrics exist immediately for scraping."""
    from study_coach.config import GEMINI_MODEL

    REQUESTS_TOTAL.labels(workflow="topic_explanation", status="success")
    REQUESTS_TOTAL.labels(workflow="study_plan_generation", status="success")
    REQUESTS_TOTAL.labels(workflow="quiz_generation", status="success")
    REQUESTS_TOTAL.labels(workflow="quiz_grading", status="success")
    AGENT_CALLS_TOTAL.labels(agent="topic_expert", model=GEMINI_MODEL)
    AGENT_CALLS_TOTAL.labels(agent="study_planner", model=GEMINI_MODEL)
    AGENT_CALLS_TOTAL.labels(agent="quiz_generator", model=GEMINI_MODEL)
    TOOL_CALLS_TOTAL.labels(tool="search_topics", status="success")
    TOOL_CALLS_TOTAL.labels(tool="validate_study_plan", status="success")
    QUIZ_SUBMISSIONS_TOTAL.labels(quiz_type="quick_check")
    QUIZ_SUBMISSIONS_TOTAL.labels(quiz_type="practice_quiz")
    AGENT_CALLS_TOTAL.labels(agent="document_agent", model=GEMINI_MODEL)
    DOCUMENT_OPERATIONS_TOTAL.labels(operation="upload", file_type="pdf", status="success")
    DOCUMENT_OPERATIONS_TOTAL.labels(operation="search", file_type="all", status="success")
    CHAT_MESSAGES_TOTAL.labels(role="student", routed_agent="coordinator")
    CHAT_MESSAGES_TOTAL.labels(role="coach", routed_agent="document_agent")


def start_metrics_server(port: int | None = None) -> bool:
    """Starts Prometheus HTTP metrics scraping server on the given port.

    Returns True if started, False if already running or failed.
    """
    global _HTTP_SERVER_STARTED
    if _HTTP_SERVER_STARTED:
        return True

    from study_coach.observability.config import ObservabilityConfig

    actual_port = (
        port if port is not None else ObservabilityConfig.from_env().metrics_port
    )
    try:
        init_metrics()
        start_http_server(port=actual_port, registry=study_coach_registry)
        _HTTP_SERVER_STARTED = True
        logger.info("Prometheus metrics server started on port %d", actual_port)
        return True
    except (OSError, RuntimeError) as err:
        logger.warning(
            "Could not start Prometheus HTTP metrics server on port %d: %s",
            actual_port,
            err,
        )
        return False
